    fun lensById(id: String): LensModel = lenses.firstOrNull { it.id == id } ?: lenses[1]
    fun bodyById(id: String): CameraBodyModel = bodies.firstOrNull { it.id == id } ?: bodies[0]
    fun filmById(id: String): FilmStockModel = films.firstOrNull { it.id == id } ?: films[0]

    fun compatibleLensesFor(body: CameraBodyModel): List<LensModel> =
        lenses.filter { body.mount in it.compatibleMounts }

    fun isLensCompatible(lens: LensModel, body: CameraBodyModel): Boolean =
        body.mount in lens.compatibleMounts

    fun defaultLensFor(body: CameraBodyModel): LensModel =
        compatibleLensesFor(body).firstOrNull { it.id == body.defaultLensId }
            ?: compatibleLensesFor(body).firstOrNull()
            ?: lenses[1]
