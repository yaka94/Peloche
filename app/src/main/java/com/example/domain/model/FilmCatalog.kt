    private fun FilmSeed.toModel(): FilmStockModel {
        val grainSize = when {
            iso <= 15 -> 0.55f
            iso <= 50 -> 0.65f
            iso <= 100 -> 0.80f
            iso <= 200 -> 0.98f
            iso <= 400 -> 1.20f
            iso <= 800 -> 1.50f
            iso <= 1600 -> 1.85f
            else -> 2.25f
        }
        val grainIntensity = when {
            iso <= 15 -> 0.09f
            iso <= 50 -> 0.07f
            iso <= 100 -> 0.11f
            iso <= 200 -> 0.16f
            iso <= 400 -> 0.22f
            iso <= 800 -> 0.30f
            iso <= 1600 -> 0.38f
            else -> 0.46f
        }
        return FilmStockModel(
            id = id,
            name = name,
            code = code,
            iso = iso,
            mood = mood,
            emulsionType = emulsion,
            canisterColorHex = canisterHex,
            stripeColorHex = stripeHex,
            labelTextHex = textHex,
            isMonochrome = isMono,
            redGain = r,
            greenGain = g,
            blueGain = b,
            contrast = contrast,
            saturation = sat,
            gamma = gamma,
            toeLift = toe,
            shoulderCompress = shoulder,
            shadowTintR = sR, shadowTintG = sG, shadowTintB = sB,
            highlightTintR = hR, highlightTintG = hG, highlightTintB = hB,
            grainSize = grainSize,
            grainIntensity = grainIntensity,
            halationBoost = halation,
            hueShift = hue,
            sepiaAmount = sepia,
            cyanotypeAmount = cyano,
            infraredAmount = ir,
            orthoUvAmount = orthoUv,
            collodionPlateAmount = collodion,
            daguerreTarnishAmount = daguerre,
            autochromeMosaicAmount = autochrome,
            paperFiberAmount = paperFiber,
            brushBorderAmount = brushBorder,
            tagline = tagline
        )
    }

